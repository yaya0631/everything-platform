/**
 * Regenerates panel/icons.js from the CAD app's Lucide package, so the panel
 * uses the same interface icons without a build step:
 *   node panel/make-icons.mjs        (after npm --prefix app install)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const lucideDir = path.join(here, '..', 'app', 'node_modules', 'lucide');
const pkg = JSON.parse(fs.readFileSync(path.join(lucideDir, 'package.json'), 'utf8'));
const L = await import(pathToFileURL(path.join(lucideDir, pkg.module || pkg.main)).href);

const NAMES = {
  gauge: 'Gauge', users: 'Users', share: 'Share2', sparkles: 'Sparkles', mail: 'Mail', apps: 'AppWindow', server: 'Server',
  history: 'History', user: 'User', key: 'KeyRound', monitor: 'MonitorSmartphone', plug: 'Plug', plus: 'Plus', trash: 'Trash2',
  copy: 'Copy', refresh: 'RefreshCw', x: 'X', check: 'Check', alert: 'TriangleAlert', info: 'Info', download: 'Download',
  upload: 'Upload', log_out: 'LogOut', external: 'ExternalLink', link: 'Link', eye: 'Eye', pencil: 'Pencil', folder: 'Folder',
  file: 'File', rotate: 'RotateCcw', send: 'Send', terminal: 'Terminal', chevron: 'ChevronRight', globe: 'Globe', lock: 'Lock',
  shield: 'ShieldCheck', arrow_left: 'ArrowLeft',
};
const nodes = {};
for (const [k, n] of Object.entries(NAMES)) {
  if (!L[n]) throw new Error(`Lucide has no icon ${n}`);
  nodes[k] = L[n];
}
const out = `/**
 * Interface icons for the panel: the same Lucide icons the CAD app uses
 * (lucide ${pkg.version}, ISC licence). Generated by panel/make-icons.mjs;
 * do not edit by hand.
 */
const NODES = ${JSON.stringify(nodes)};

const NS = 'http://www.w3.org/2000/svg';

/** icon('users', 16) → <svg class="icon" aria-hidden="true"> */
export function icon(name, size = 16) {
  const svg = document.createElementNS(NS, 'svg');
  const attrs = { width: size, height: size, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', class: 'icon', 'aria-hidden': 'true' };
  for (const [k, v] of Object.entries(attrs)) svg.setAttribute(k, v);
  for (const [tag, a] of NODES[name] || []) {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(a)) el.setAttribute(k, v);
    svg.append(el);
  }
  return svg;
}
`;
fs.writeFileSync(path.join(here, 'icons.js'), out);
console.log(`Wrote panel/icons.js with ${Object.keys(nodes).length} icons.`);
